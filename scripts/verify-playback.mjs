import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser=await chromium.launch({channel:'chromium',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const dialogGone=()=>page.locator('dialog').waitFor({state:'detached'});
const settings=async (repeat,advance=false)=>{
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('switch',{name:'Autoplay',exact:true}).uncheck();
  await page.getByRole('switch',{name:'Autoplay next',exact:true}).setChecked(advance);
  await page.getByRole('combobox',{name:'Repeat',exact:true}).selectOption(repeat);
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await dialogGone();
};
const loaded=()=>page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
const finish=async()=>{await loaded();await page.locator('video').evaluate(async v=>{v.currentTime=v.duration-0.2;await v.play();});};
try {
  await page.goto('http://127.0.0.1:5173');
  await settings('one');
  const buffer=await readFile('tests/fixtures/sample.mp4');
  await page.locator('input[type=file]').first().setInputFiles([{name:'First.mp4',mimeType:'video/mp4',buffer},{name:'Second.mp4',mimeType:'video/mp4',buffer}]);
  await loaded();assert.equal(await page.locator('video').evaluate(v=>v.loop),true);
  await finish();await page.waitForFunction(()=>{const v=document.querySelector('video');return v.currentTime<2&&!v.paused;});
  assert.equal(await page.locator('.player-heading h1').innerText(),'First.mp4');
  await page.locator('video').evaluate(v=>v.pause());
  await page.getByRole('button',{name:'Repeat: One',exact:true}).click();
  await page.getByRole('button',{name:'Repeat: All',exact:true}).waitFor();
  assert.equal(await page.locator('video').evaluate(v=>v.loop),false);
  await finish();await page.getByRole('heading',{name:'Second.mp4',exact:true}).waitFor();
  await page.waitForFunction(()=>{const v=document.querySelector('video');return v.readyState>=2&&!v.paused&&v.currentTime<2;});
  await finish();await page.getByRole('heading',{name:'First.mp4',exact:true}).waitFor();await loaded();
  await page.locator('video').evaluate(v=>v.pause());
  await page.reload();
  await page.locator('.library-section').waitFor();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  assert.equal(await page.getByRole('combobox',{name:'Repeat'}).inputValue(),'all');
  assert.equal(await page.getByRole('switch',{name:'Autoplay',exact:true}).isChecked(),false);
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await dialogGone();
  await page.locator('.library-toolbar summary[aria-label="Sort by"]').click();
  await page.getByRole('button',{name:'Name',exact:true}).click();
  await page.getByRole('button',{name:'Play First.mp4'}).click();await loaded();
  await settings('off');
  await finish();await page.waitForFunction(()=>document.querySelector('video').ended);
  assert.equal(await page.locator('.player-heading h1').innerText(),'First.mp4');
  await settings('off',true);await finish();await page.getByRole('heading',{name:'Second.mp4',exact:true}).waitFor();
  await finish();await page.waitForFunction(()=>document.querySelector('video').ended);
  assert.equal(await page.locator('.player-heading h1').innerText(),'Second.mp4');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('combobox',{name:'Appearance'}).selectOption('dark');
  await page.getByRole('combobox',{name:'Repeat'}).selectOption('all');
  await page.screenshot({path:'/tmp/videe-playback-settings.png',fullPage:true});
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await dialogGone();
  assert.ok(await page.evaluate(()=>document.querySelector('.player-controls').getBoundingClientRect().bottom<=innerHeight), 'mobile controls fit vertically');
  await page.screenshot({path:'/tmp/videe-playback-mobile.png',fullPage:true});
  // A one-item filtered queue must also repeat, without loading a new source.
  await page.getByRole('button',{name:'Back to library'}).click();
  await page.getByRole('searchbox',{name:'Search videos'}).fill('First');
  await page.getByRole('button',{name:'Play First.mp4'}).click();await finish();
  await page.waitForFunction(()=>{const v=document.querySelector('video');return v.currentTime<2&&!v.paused;});
  await page.locator('video').evaluate(v=>v.pause());
  await page.evaluate(()=>localStorage.setItem('videe-preferences',JSON.stringify({speed:-5,volume:999,theme:'bad',repeat:'bad'})));
  await page.reload();await page.getByRole('button',{name:'Play First.mp4'}).click();await loaded();
  assert.equal(await page.locator('video').evaluate(v=>v.playbackRate),1);
  assert.equal(await page.locator('video').evaluate(v=>v.volume),1);
  const manifest=await page.request.get('http://127.0.0.1:5173/manifest.webmanifest');assert.equal(manifest.status(),200);
  for(const icon of (await manifest.json()).icons) assert.equal((await page.request.get('http://127.0.0.1:5173/'+icon.src)).status(),200);
  assert.deepEqual(errors,[]);
  console.log('PASS: actual single/all repeat, queue wrap, one-item queue, independent auto advance, stop at last video, saved repeat, malformed preference recovery, icon URLs, mobile controls/settings.');
} finally {await browser.close();}
