import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chromium',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const dialogGone=()=>page.locator('dialog').waitFor({state:'detached'});
try {
 await page.goto('http://127.0.0.1:5173');
 const buffer=await readFile('tests/fixtures/sample.mp4');
 await page.locator('input[type=file]').first().setInputFiles([{name:'First.mp4',mimeType:'video/mp4',buffer}]);
 await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
 await page.getByRole('button',{name:'Edit video',exact:true}).click();
 await page.locator('.editor-panel').waitFor();
 await page.locator('video').evaluate(v=>{v.pause();v.currentTime=1;});
 await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-1)<0.05);
 await page.getByRole('button',{name:/^Mark in/}).click();
 await page.locator('video').evaluate(v=>{v.currentTime=3;});
 await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-3)<0.05);
 await page.getByRole('button',{name:/^Mark out/}).click();
 assert.equal(await page.locator('.segment-row:not(.segment-head)').count(),1);
 assert.match(await page.getByRole('textbox',{name:'Segment 1 in',exact:true}).inputValue(),/^00:00:01:/);
 assert.equal(await page.locator('.seek-segments span').count(),1);
 await page.locator('video').evaluate(v=>{v.currentTime=2;});
 await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-2)<0.05);
 await page.getByRole('button',{name:/^Split/}).click();
 assert.equal(await page.locator('.segment-row:not(.segment-head)').count(),2);
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 assert.equal(await page.locator('.segment-row:not(.segment-head)').count(),1);
 await page.getByRole('button',{name:'Redo',exact:true}).click();
 assert.equal(await page.locator('.segment-row:not(.segment-head)').count(),2);
 await page.getByRole('button',{name:'Export…',exact:true}).click();
 await page.getByText('Exporting needs the Videe desktop app.').waitFor();
 assert.equal(await page.locator('dialog').getByRole('button',{name:'Export',exact:true}).isDisabled(),true);
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await dialogGone();
 await page.getByRole('button',{name:'Close editor',exact:true}).first().click();
 assert.equal(await page.locator('.editor-panel').count(),0);
 // Keyboard: E toggles the editor, I/O mark, S splits.
 await page.locator('video').evaluate(v=>{v.currentTime=0.5;});
 await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-0.5)<0.05);
 await page.evaluate(()=>document.activeElement?.blur?.());
 await page.keyboard.press('e');
 await page.locator('.editor-panel').waitFor();
 await page.keyboard.press('s');
 assert.ok(await page.locator('.segment-row:not(.segment-head)').count() >= 2);
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 assert.equal(await page.locator('.segment-row:not(.segment-head)').count(),0);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 console.log('PASS: editor marks, timecode fields, split, undo/redo, keyboard, reset, export needs app, narrow layout.');
} catch(e){ console.log(errors); await page.screenshot({path:'/tmp/videe-editor-failure.png'}); throw e; } finally { await browser.close(); }
